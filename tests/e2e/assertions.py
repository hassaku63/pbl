# coding: utf-8
"""
Assertion helpers for the end-to-end tests.

They check only the minimal structure a test needs, and their failure messages never contain
values from API responses: those may include personal data (names, mail addresses) and the
messages end up in public CI logs. See tests/e2e/README.md.

Do not use unittest's self.assert* methods in tests/e2e: on failure they print the compared
values (e.g. assertIn("id", user) prints the whole user). tests/test_e2e_support.py enforces this.
"""


def _type_name(value):
    return type(value).__name__


def has_keys(obj, *keys, what="response"):
    """
    Assert that obj is a dict that contains all the keys.
    """
    if not isinstance(obj, dict):
        raise AssertionError("{} is not an object (got {})".format(what, _type_name(obj)))
    missing = [k for k in keys if k not in obj]
    if missing:
        raise AssertionError("{} is missing key(s): {}".format(what, ", ".join(missing)))


def field_equals(obj, key, expected, what="response"):
    """
    Assert that obj[key] equals a value the test chose itself (e.g. a summary it sent).
    The message names the field only, never the values.
    """
    has_keys(obj, key, what=what)
    if obj[key] != expected:
        raise AssertionError("{}: field '{}' does not have the expected value".format(what, key))


def field_type(obj, key, expected_type, what="response"):
    """
    Assert that obj[key] has the expected type, e.g. an ID generated by the API is an int.
    """
    has_keys(obj, key, what=what)
    if not isinstance(obj[key], expected_type):
        raise AssertionError("{}: field '{}' is {}, not {}".format(
            what, key, _type_name(obj[key]), getattr(expected_type, "__name__", str(expected_type))))


def is_list(obj, what="response", min_length=0, item_keys=()):
    """
    Assert that obj is a list with at least min_length items, whose items contain item_keys.
    """
    if not isinstance(obj, list):
        raise AssertionError("{} is not a list (got {})".format(what, _type_name(obj)))
    if len(obj) < min_length:
        raise AssertionError("{} has {} item(s), expected at least {}".format(what, len(obj), min_length))
    for i, item in enumerate(obj):
        if item_keys:
            has_keys(item, *item_keys, what="{}[{}]".format(what, i))


def is_count(obj, what="response", expected=None):
    """
    Assert that obj is {"count": <int>}, optionally with a specific count.
    """
    field_type(obj, "count", int, what=what)
    if expected is not None and obj["count"] != expected:
        raise AssertionError("{}: count is {}, expected {}".format(what, obj["count"], expected))


def contains_id(items, id_, what="response"):
    """
    Assert that a list of objects contains one with the given "id" (an ID the test created).
    """
    is_list(items, what=what, item_keys=("id",))
    if id_ not in [item["id"] for item in items]:
        raise AssertionError("{} does not contain the expected item".format(what))


def is_true(condition, message):
    """
    Assert a condition with a message written by the test (it must not include response values).
    """
    if not condition:
        raise AssertionError(message)
